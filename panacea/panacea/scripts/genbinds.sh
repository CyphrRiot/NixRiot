#!/bin/bash
#

CFG="$HOME/.config/panacea/settings.json"
OUT="$HOME/.config/hypr/lua/binds_data.lua"

[ -f "$CFG" ] || exit 1

tmp="$OUT.new"

{
    echo "-- File is generated by the pill settings panel (Super+I)."
    echo "-- Manual edits are overwritten on the next binding change."
    echo "return {"
    jq -r '
        to_entries
        | map(select(.key | startswith("bind_")))
        | sort_by(.key)
        | .[]
        | "    [\"" + (.key | sub("^bind_"; "")) + "\"] = " + (.value | tostring | @json) + ","
    ' "$CFG"
    echo "}"
} > "$tmp"

# A reload re-runs the whole Hyprland config, which re-applies the display rules
# and modesets every output. During an update that is a visible black frame, and
# nothing about the bindings changed, so only reload when the file really moved.
if cmp -s "$tmp" "$OUT"; then
    rm -f "$tmp"
else
    mv -f "$tmp" "$OUT"
    hyprctl reload >/dev/null 2>&1
fi
